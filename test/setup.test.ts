import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DEFAULT_TITLES, parseConfig } from '../src/config.ts';
import { applyAnswers, colorOverrides, LAUNCHERS, parseIdInput, sourcesMarkdown, type SetupAnswers } from '../src/setup-core.ts';
import { CANVAS_1440P, scaleRect } from '../src/sources.ts';
import { resolveTheme } from '../src/theme.ts';

const example = () => JSON.parse(readFileSync(new URL('../config.example.json', import.meta.url), 'utf8')) as Record<string, unknown>;
const answers = (over: Partial<SetupAnswers> = {}): SetupAnswers => ({
	participantId: '581000', teamId: 'MyTeam', timeZone: 'America/New_York', start: '2026-11-07T09:00', end: '2026-11-08T09:00',
	style: 'framed', donations: 'messages', intervalSeconds: 60, titles: { ...DEFAULT_TITLES }, themePreset: 'midnight',
	themeColors: {}, port: 4300, ...over,
});

test('parseIdInput accepts IDs, aliases, and pasted page URLs', () => {
	assert.equal(parseIdInput('581864'), '581864');
	assert.equal(parseIdInput(' https://dd.extra-life.org/participants/581864 '), '581864');
	assert.equal(parseIdInput('https://dd.extra-life.org/teams/GamePlan42'), 'GamePlan42');
	assert.equal(parseIdInput('https://www.extra-life.org/participants/581864/donate'), '581864');
	assert.equal(parseIdInput('my team!'), 'myteam');
});

test('applyAnswers writes the answers and keeps every other setting', () => {
	const base = example();
	(base.messageFilter as Record<string, unknown>).extraWords = ['spoiler'];
	const out = applyAnswers(base, answers());
	const c = parseConfig(out);
	assert.equal(c.extraLife.participantId, '581000');
	assert.equal(c.event.timeZone, 'America/New_York');
	assert.equal(c.display.style, 'framed');
	assert.equal(c.display.donations, 'messages');
	assert.equal(c.rotation.intervalSeconds, 60);
	assert.equal(c.server.port, 4300);
	assert.equal(c.theme.preset, 'midnight');
	assert.deepEqual(c.messageFilter.extraWords, ['spoiler']); // untouched
	assert.equal(c.polling.participantSeconds, 15); // untouched
	assert.equal(c.extraLife.baseUrl, 'https://dd.extra-life.org/api'); // untouched
	assert.notEqual(base, out); // base not mutated
	assert.equal((base.server as Record<string, unknown>).port, 4242);
});

test('colorOverrides keeps only colors that differ from the preset', () => {
	const colors = resolveTheme('extra-life', { primary: '#c0ffee' });
	assert.deepEqual(colorOverrides('extra-life', colors), { primary: '#C0FFEE' });
	assert.deepEqual(colorOverrides('extra-life', resolveTheme('extra-life')), {});
});

test('MY-SOURCES.md lists the right sources and sizes for the style', () => {
	const framed = parseConfig(applyAnswers(example(), answers()));
	const md = sourcesMarkdown(framed, new Date('2026-10-21T12:00:00Z'));
	assert.match(md, /Generated by `npm run setup` on 2026-10-21/);
	assert.match(md, /\| Stream countdown \| `http:\/\/localhost:4300\/widgets\/countdown` \| 494 × 128 at 20, 944 \| 659 × 171 at 27, 1259 \|/);
	assert.match(md, /donation-messages` \| 320 × 143 at 1580, 290 \| 427 × 191 at 2107, 387 \|/);
	assert.match(md, /Shutdown source when not visible\*\* off/);
	assert.match(md, /\| Be Right Back scene \| `http:\/\/localhost:4300\/scenes\/be-right-back` \| 1920 × 1080 at 0, 0 \| 2560 × 1440 at 0, 0 \|/);
	assert.match(md, /\| Be Right Back scene \(light\) \| `http:\/\/localhost:4300\/scenes\/be-right-back\?look=light` \| 1920 × 1080 at 0, 0 \| 2560 × 1440 at 0, 0 \|/);
	assert.match(md, /\| Ending scene \| `http:\/\/localhost:4300\/scenes\/ending` \| 1920 × 1080 at 0, 0 \| 2560 × 1440 at 0, 0 \|/);
	assert.match(md, /\| Ending scene \(light\) \| `http:\/\/localhost:4300\/scenes\/ending\?look=light` \| 1920 × 1080 at 0, 0 \| 2560 × 1440 at 0, 0 \|/);
	assert.match(md, /Image\*\*, file `public\/scenes\/starting-soon\/starting-soon\.gif`/);
	assert.match(md, /streamingOverlay&eventID=553&participantID=581000`, 1920 × 88 at 0, 992 \(1080p\) or 2560 × 117 at 0, 1323 \(1440p\)/);

	const transparent = parseConfig(applyAnswers(example(), answers({ style: 'transparent', donations: 'standard' })));
	const md2 = sourcesMarkdown(transparent);
	assert.match(md2, /countdown` \| 488 × 82 at 23, 987 \| 651 × 109 at 31, 1316 \|/);
	assert.match(md2, /donation-rotator` \| 314 × 58 at 1583, 325 \| 419 × 77 at 2111, 433 \|/);
	assert.doesNotMatch(md2, /donation-messages/);
});

test('scaleRect: 1440p numbers are the 1080p design times 4/3, rounded', () => {
	assert.deepEqual(scaleRect({ x: 0, y: 0, w: 1920, h: 1080 }, CANVAS_1440P.scale), { x: 0, y: 0, w: 2560, h: 1440 });
	assert.deepEqual(scaleRect({ x: 23, y: 987, w: 488, h: 82 }, CANVAS_1440P.scale), { x: 31, y: 1316, w: 651, h: 109 });
});

test('launchers start the server from their own folder', () => {
	assert.match(LAUNCHERS['start-widgets.command'], /^#!\/bin\/bash/);
	assert.match(LAUNCHERS['start-widgets.command'], /cd "\$\(dirname "\$0"\)"/);
	assert.match(LAUNCHERS['start-widgets.command'], /caffeinate -is npm start/);
	assert.match(LAUNCHERS['start-widgets.bat'], /cd \/d "%~dp0"\r\n/);
	assert.match(LAUNCHERS['start-widgets.bat'], /\r\ncall npm start\r\npause\r\n/);
});
