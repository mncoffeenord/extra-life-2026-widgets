// Pure pieces of `npm run setup` (kept apart from the prompts so they can be tested).

import type { Config, Titles } from './config.ts';
import { scenesFor, sourcesFor } from './sources.ts';
import { THEME_KEYS, THEME_PRESETS, type ThemeColors, type ThemeRegistry } from './theme.ts';

export interface SetupAnswers {
	participantId: string;
	teamId: string;
	timeZone: string;
	start: string;
	end: string;
	style: 'framed' | 'transparent';
	donations: 'standard' | 'messages';
	intervalSeconds: number;
	titles: Titles;
	themePreset: string;
	/** only the colors that differ from the preset */
	themeColors: Partial<ThemeColors>;
	port: number;
}

type Json = Record<string, unknown>;

/** Accept a bare ID/alias or a pasted page URL (".../participants/581864" or ".../teams/GamePlan42"). */
export function parseIdInput(input: string): string {
	const trimmed = input.trim();
	const fromUrl = /\/(?:participants|teams)\/([A-Za-z0-9_-]+)/.exec(trimmed);
	return fromUrl ? fromUrl[1]! : trimmed.replace(/[^A-Za-z0-9_-]/g, '');
}

/** Write the answers into a copy of the base config, keeping every other setting (polling, filter words...). */
export function applyAnswers(base: Json, a: SetupAnswers): Json {
	const c = structuredClone(base) as Record<string, Json>;
	const section = (name: string): Json => (c[name] = typeof c[name] === 'object' && c[name] !== null ? c[name] : {});
	Object.assign(section('server'), { port: a.port });
	Object.assign(section('extraLife'), { participantId: a.participantId, teamId: a.teamId });
	Object.assign(section('event'), { timeZone: a.timeZone, start: a.start, end: a.end });
	Object.assign(section('rotation'), { intervalSeconds: a.intervalSeconds });
	Object.assign(section('display'), { style: a.style, donations: a.donations, titles: { ...a.titles } });
	c.theme = { preset: a.themePreset, colors: { ...a.themeColors } };
	return c;
}

/** Colors that differ from the preset, so config.json only lists real overrides. */
export function colorOverrides(preset: string, colors: ThemeColors, registry: ThemeRegistry = THEME_PRESETS): Partial<ThemeColors> {
	const base = registry[preset];
	const out: Partial<ThemeColors> = {};
	for (const key of THEME_KEYS) if (!base || base[key].toUpperCase() !== colors[key].toUpperCase()) out[key] = colors[key];
	return out;
}

/** MY-SOURCES.md: the browser sources for this setup, ready to copy into Streamlabs or OBS. */
export function sourcesMarkdown(config: Config, now = new Date()): string {
	const rows = sourcesFor(config);
	const framed = config.display.style === 'framed';
	const lines = [
		'# My browser sources',
		'',
		`Generated by \`npm run setup\` on ${now.toISOString().slice(0, 10)}. Re-run it to change anything, or edit \`config.json\`.`,
		'',
		`Style: **${config.display.style}**. ${framed
			? 'Each widget draws its own box, so you can place it anywhere.'
			: 'Each widget fills the white area of a box drawn in your overlay art.'}`,
		`Colors: **${config.theme.preset}** theme${Object.keys(config.theme.colors).length ? ' with custom colors' : ''}. Rotation: every ${config.rotation.intervalSeconds} s.`,
		'',
		'Start the server before opening Streamlabs: double-click `start-widgets.command` (Mac) or `start-widgets.bat` (Windows), or run `npm start`.',
		'',
		'| Source | URL | Width × Height | Position X, Y (GamePlan42 layout) |',
		'| --- | --- | --- | --- |',
		...rows.map((r) => `| ${r.name} | \`${r.url}\` | ${r.rect.w} × ${r.rect.h} | ${r.rect.x}, ${r.rect.y} |`),
		'',
		framed
			? 'Positions place the boxes where the GamePlan42 overlay has them; with framed widgets you can put them anywhere.'
			: 'Positions match the GamePlan42 overlay art. On a different overlay, size each source to the white area it should fill.',
		'',
		'## In Streamlabs (or OBS)',
		'',
		'For each row: **+ Add Source → Browser Source**, then:',
		'',
		'- Leave **Local file** off and paste the URL.',
		'- Set **Width** and **Height** from the table.',
		'- Leave **Custom CSS** at its default.',
		'- Turn **Shutdown source when not visible** off.',
		'- Position it (right-click → Transform → Edit Transform), at 100% scale.',
		'',
		'## Scenes (optional)',
		'',
		'Full-screen pages for breaks. Put each on **its own Streamlabs scene** and switch to it when you step away.',
		'They keep their own colors (the theme does not apply). Be Right Back comes in two looks: use one of the two rows.',
		'',
		'| Scene | URL | Width × Height | Position X, Y |',
		'| --- | --- | --- | --- |',
		...scenesFor(config).map((s) => `| ${s.name} | \`${s.url}\` | ${s.rect.w} × ${s.rect.h} | ${s.rect.x}, ${s.rect.y} |`),
		'',
		'Same Browser Source settings as above, plus **FPS** 30. Add `?mock=1` to the URL to check it with sample data.',
		'',
		`Check everything at \`http://localhost:${config.server.port}/preview/\` (mock data: \`npm run mock\`).`,
		'',
	];
	return lines.join('\n');
}

